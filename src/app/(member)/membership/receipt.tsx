import React from 'react';
import { Platform, View } from 'react-native';
import { useLocalSearchParams } from 'expo-router';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { AppText, Badge, Banner, Button, Card, EmptyState, KeyValue, Loading, Screen, useBusy } from '../../../components/ui';
import { useAuth } from '../../../lib/auth';
import { useDocData } from '../../../lib/db';
import { fmtDateTime, money } from '../../../lib/format';
import type { Payment } from '../../../lib/types';
import { statusTone } from '../../../lib/payments';

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

function receiptHtml(p: Payment, name: string, email: string) {
  const rows = [
    ['Receipt / Transaction ID', p.txnId],
    ['Member', `${name} (${email})`],
    ['Plan', p.planName],
    ['Amount', money(p.amount, p.currency)],
    ['Payment method', p.method.toUpperCase()],
    ['Gateway', p.gateway],
    ['Status', p.status.toUpperCase()],
    ['Date', fmtDateTime(p.createdAt)],
  ];
  return `<html><head><meta charset="utf-8"/><title>FitTrack receipt</title></head>
<body style="font-family:Arial,sans-serif;padding:32px;color:#111">
<h1 style="margin:0">Fit<span style="color:#E50914">Track</span></h1>
<p style="color:#666;margin-top:4px">Payment receipt</p>
<hr/>
<table style="width:100%;border-collapse:collapse">
${rows.map(([k, v]) => `<tr><td style="padding:8px 0;color:#666;width:40%">${esc(k)}</td><td style="padding:8px 0;font-weight:bold">${esc(String(v))}</td></tr>`).join('')}
</table>
<hr/>
<p style="color:#888;font-size:12px">This receipt was generated by FitTrack. ${p.gateway === 'mock' ? 'SANDBOX / TEST payment — no real money was charged.' : ''}</p>
</body></html>`;
}

export default function Receipt() {
  const { id } = useLocalSearchParams<{ id: string }>();
  const { user, profile } = useAuth();
  const pay = useDocData<Payment>(id ? `payments/${id}` : null);
  const { busy, run } = useBusy();
  const p = pay.data;

  const download = () =>
    run(async () => {
      if (!p) return;
      const html = receiptHtml(p, profile?.name || user?.displayName || 'Member', user?.email || '');
      if (Platform.OS === 'web') {
        await Print.printAsync({ html }); // opens the browser print dialog (choose "Save as PDF")
      } else {
        const { uri } = await Print.printToFileAsync({ html });
        if (await Sharing.isAvailableAsync()) await Sharing.shareAsync(uri, { mimeType: 'application/pdf', dialogTitle: 'FitTrack receipt' });
      }
    });

  return (
    <Screen title="Receipt" back="/membership">
      {pay.loading ? (
        <Loading />
      ) : !p ? (
        <EmptyState icon="receipt-text-remove-outline" title="Receipt not found" />
      ) : (
        <Card>
          <View style={{ alignItems: 'flex-start', marginBottom: 10 }}><Badge text={p.status.toUpperCase()} tone={statusTone(p.status)} /></View>
          <AppText variant="big">{money(p.amount, p.currency)}</AppText>
          <View style={{ height: 12 }} />
          <KeyValue label="Transaction ID" value={p.txnId} />
          <KeyValue label="Plan" value={p.planName} />
          <KeyValue label="Method" value={p.method.toUpperCase()} />
          <KeyValue label="Gateway" value={p.gateway} />
          <KeyValue label="Date" value={fmtDateTime(p.createdAt)} />
          {p.verifiedAt ? <KeyValue label="Verified" value={fmtDateTime(p.verifiedAt)} /> : null}
          {p.gateway === 'mock' ? <View style={{ marginTop: 12 }}><Banner tone="info" text="Sandbox payment — no real money was charged." /></View> : null}
          <Button title={Platform.OS === 'web' ? 'Print / save as PDF' : 'Download receipt (PDF)'} icon="download" onPress={download} loading={busy} full style={{ marginTop: 16 }} />
        </Card>
      )}
    </Screen>
  );
}
